#!/usr/bin/env python3
"""Generate the ring serial protocol for both sides from protocol.yaml.

    python3 comms/gen_protocol.py           write both files
    python3 comms/gen_protocol.py --check   exit 1 if either file is out of date

Outputs (both committed to git; neither build runs this script):
    arduino/ring_stepper/ring_protocol.h
    colcon/ros2_ws/src/apollo_ring/apollo_ring/ring_protocol.py

Needs only Python 3 and PyYAML (pip install pyyaml).
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
SCHEMA = ROOT / "comms" / "protocol.yaml"
OUT_H = ROOT / "arduino" / "ring_stepper" / "ring_protocol.h"
OUT_PY = ROOT / "colcon" / "ros2_ws" / "src" / "apollo_ring" / "apollo_ring" / "ring_protocol.py"

# schema type -> (C++ type, struct code, size in bytes)
TYPES = {
    "u8": ("uint8_t", "B", 1),
    "i8": ("int8_t", "b", 1),
    "u16": ("uint16_t", "H", 2),
    "i16": ("int16_t", "h", 2),
    "u32": ("uint32_t", "I", 4),
    "i32": ("int32_t", "i", 4),
    "f32": ("float", "f", 4),
}

BANNER = "GENERATED by comms/gen_protocol.py from comms/protocol.yaml. Do not edit; edit the schema and regenerate."


def camel(name: str) -> str:
    return "".join(p.capitalize() for p in name.lower().split("_"))


def load() -> dict:
    s = yaml.safe_load(SCHEMA.read_text())
    max_payload = s["constants"]["MAX_PAYLOAD"]
    seen = set()
    for name, m in s["messages"].items():
        if m["type"] in seen:
            sys.exit(f"protocol.yaml: duplicate message type 0x{m['type']:02X} ({name})")
        seen.add(m["type"])
        m.setdefault("fields", [])
        for f in m["fields"]:
            if not isinstance(f["name"], str):
                sys.exit(f"protocol.yaml: {name}: field name {f['name']!r} is not a string (YAML reads on/off/yes/no as booleans)")
            if f["type"] not in TYPES:
                sys.exit(f"protocol.yaml: {name}.{f['name']}: unknown type {f['type']}")
            if "enum" in f and f["enum"] not in s["enums"]:
                sys.exit(f"protocol.yaml: {name}.{f['name']}: unknown enum {f['enum']}")
        m["len"] = sum(TYPES[f["type"]][2] for f in m["fields"])
        if m["len"] > max_payload:
            sys.exit(f"protocol.yaml: {name} payload {m['len']} B exceeds MAX_PAYLOAD {max_payload}")
    return s


# ---------------------------------------------------------------------------- C++

def gen_h(s: dict) -> str:
    c = s["constants"]
    o = [f"// {BANNER}", "//", "// Apollo ring stepper: Pi <-> Arduino serial protocol.", "//",
         "// Frame:  0xAA 0x55 | type | len | payload[len] | crc8",
         "// CRC-8/MAXIM over type, len and payload. Little-endian; f32 = IEEE-754 float32.", "//"]
    for name, m in s["messages"].items():
        arrow = "Pi -> Arduino" if m["dir"] == "to_mcu" else "Arduino -> Pi"
        o.append(f"//   0x{m['type']:02X} {name:<11} {arrow:<14} {m['len']:>2} B  {m['doc']}")
    o += ["#pragma once", "#include <stdint.h>", "#include <string.h>", "", "namespace ring {", ""]

    for k, v in c.items():
        ctype = "uint32_t" if (k.endswith("_MS") or k.endswith("_BAUD") or v > 255) else "uint8_t"
        lit = f"0x{v:02X}" if k.startswith("SYNC") else str(v)
        o.append(f"const {ctype} {k} = {lit};")
    o += ["const uint8_t MAX_FRAME = MAX_PAYLOAD + 5;", ""]

    o.append("enum MsgType : uint8_t {")
    for name, m in s["messages"].items():
        o.append(f"  {name} = 0x{m['type']:02X},")
    o += ["};", ""]

    for ename, e in s["enums"].items():
        prefix = e.get("prefix", "")
        o.append(f"enum {ename} : uint8_t {{")
        for vname, v in e["values"].items():
            lit = f"0x{v:02X}" if e.get("bitfield") else str(v)
            o.append(f"  {prefix}{vname} = {lit},")
        o += ["};", ""]

    for name, m in s["messages"].items():
        o.append(f"const uint8_t {name}_LEN = {m['len']};")
    o.append("")

    o += [
        "inline uint8_t crc8_update(uint8_t crc, uint8_t b) {",
        "  crc ^= b;",
        "  for (uint8_t i = 0; i < 8; i++) crc = (crc & 1) ? (crc >> 1) ^ 0x8C : (crc >> 1);",
        "  return crc;",
        "}",
        "",
        "// Writes a complete frame into out (at least len + 5 bytes); returns its length.",
        "inline uint8_t encode(uint8_t type, const uint8_t* payload, uint8_t len, uint8_t* out) {",
        "  out[0] = SYNC0;",
        "  out[1] = SYNC1;",
        "  out[2] = type;",
        "  out[3] = len;",
        "  if (len) memcpy(out + 4, payload, len);",
        "  uint8_t crc = 0;",
        "  for (uint8_t i = 2; i < (uint8_t)(len + 4); i++) crc = crc8_update(crc, out[i]);",
        "  out[4 + len] = crc;",
        "  return len + 5;",
        "}",
        "",
        "// Typed messages. pack()/unpack() copy fields at fixed offsets (both AVR and",
        "// SAMD are little-endian, so memcpy gives the wire byte order).",
    ]
    for name, m in s["messages"].items():
        if not m["fields"]:
            continue
        st = camel(name) + "Msg"
        o.append(f"struct {st} {{")
        for f in m["fields"]:
            ctype = f["enum"] if "enum" in f and not s["enums"][f["enum"]].get("bitfield") else TYPES[f["type"]][0]
            o.append(f"  {ctype} {f['name']};")
        o += ["};", ""]
        o.append(f"inline uint8_t pack(const {st}& m, uint8_t* out) {{")
        off = 0
        for f in m["fields"]:
            o.append(f"  memcpy(out + {off}, &m.{f['name']}, {TYPES[f['type']][2]});")
            off += TYPES[f["type"]][2]
        o += [f"  return {name}_LEN;", "}", ""]
        o.append(f"inline bool unpack(const uint8_t* p, uint8_t len, {st}& m) {{")
        o.append(f"  if (len != {name}_LEN) return false;")
        off = 0
        for f in m["fields"]:
            o.append(f"  memcpy(&m.{f['name']}, p + {off}, {TYPES[f['type']][2]});")
            off += TYPES[f["type"]][2]
        o += ["  return true;", "}", ""]
        o.append(f"inline uint8_t encode(const {st}& m, uint8_t* out) {{")
        o.append(f"  uint8_t p[{name}_LEN];")
        o.append("  pack(m, p);")
        o.append(f"  return encode({name}, p, {name}_LEN, out);")
        o += ["}", ""]

    o += [
        "// Byte-at-a-time frame parser. feed() returns true when a frame with a good",
        "// CRC has just completed; type, len and payload are then valid.",
        "struct Parser {",
        "  uint8_t type = 0;",
        "  uint8_t len = 0;",
        "  uint8_t payload[MAX_PAYLOAD];",
        "",
        "  bool feed(uint8_t b) {",
        "    switch (stage_) {",
        "      case 0:",
        "        if (b == SYNC0) stage_ = 1;",
        "        return false;",
        "      case 1:",
        "        stage_ = (b == SYNC1) ? 2 : (b == SYNC0 ? 1 : 0);",
        "        return false;",
        "      case 2:",
        "        type = b;",
        "        crc_ = crc8_update(0, b);",
        "        stage_ = 3;",
        "        return false;",
        "      case 3:",
        "        if (b > MAX_PAYLOAD) { stage_ = 0; return false; }",
        "        len = b;",
        "        idx_ = 0;",
        "        crc_ = crc8_update(crc_, b);",
        "        stage_ = len ? 4 : 5;",
        "        return false;",
        "      case 4:",
        "        payload[idx_++] = b;",
        "        crc_ = crc8_update(crc_, b);",
        "        if (idx_ >= len) stage_ = 5;",
        "        return false;",
        "      default:",
        "        stage_ = 0;",
        "        return b == crc_;",
        "    }",
        "  }",
        "",
        " private:",
        "  uint8_t stage_ = 0;",
        "  uint8_t idx_ = 0;",
        "  uint8_t crc_ = 0;",
        "};",
        "",
        "}  // namespace ring",
        "",
    ]
    return "\n".join(o)


# ------------------------------------------------------------------------- Python

def gen_py(s: dict) -> str:
    c = s["constants"]
    o = [
        f'"""Apollo ring stepper: Pi <-> Arduino serial protocol.',
        "",
        f"{BANNER}",
        "No ROS imports, so the bench tools and tests can use it on their own.",
        "",
        "Frame:  0xAA 0x55 | type | len | payload[len] | crc8   (CRC-8/MAXIM, little-endian)",
        '"""',
        "from __future__ import annotations",
        "",
        "import struct",
        "from dataclasses import dataclass",
        "from enum import IntEnum, IntFlag",
        "from typing import ClassVar, Dict, Iterator, Optional, Tuple, Type",
        "",
    ]
    for k, v in c.items():
        o.append(f"{k} = 0x{v:02X}" if k.startswith("SYNC") else f"{k} = {v}")
    o += ["MAX_FRAME = MAX_PAYLOAD + 5", "SYNC = bytes([SYNC0, SYNC1])", ""]
    for name, m in s["messages"].items():
        o.append(f"{name} = 0x{m['type']:02X}")
    o += ["", ""]

    for ename, e in s["enums"].items():
        base = "IntFlag" if e.get("bitfield") else "IntEnum"
        o.append(f"class {ename}({base}):")
        for vname, v in e["values"].items():
            o.append(f"    {vname} = {f'0x{v:02X}' if e.get('bitfield') else v}")
        o += ["", ""]

    o += [
        "def crc8(data: bytes) -> int:",
        "    crc = 0",
        "    for b in data:",
        "        crc ^= b",
        "        for _ in range(8):",
        "            crc = (crc >> 1) ^ 0x8C if crc & 1 else crc >> 1",
        "    return crc",
        "",
        "",
        'def encode(msg_type: int, payload: bytes = b"") -> bytes:',
        "    if len(payload) > MAX_PAYLOAD:",
        '        raise ValueError(f"payload {len(payload)} B exceeds MAX_PAYLOAD")',
        "    body = bytes([msg_type, len(payload)]) + payload",
        "    return SYNC + body + bytes([crc8(body)])",
        "",
        "",
    ]

    for name, m in s["messages"].items():
        cls = camel(name)
        fmt = "<" + "".join(TYPES[f["type"]][1] for f in m["fields"])
        o += ["@dataclass(frozen=True)", f"class {cls}:", f'    """{m["doc"]}"""', ""]
        o.append(f"    TYPE: ClassVar[int] = {name}")
        o.append(f"    LEN: ClassVar[int] = {m['len']}")
        o.append(f'    _STRUCT: ClassVar[struct.Struct] = struct.Struct("{fmt}")')
        if m["fields"]:
            o.append("")
        for f in m["fields"]:
            pyt = f.get("enum") or ("float" if f["type"] == "f32" else "int")
            o.append(f"    {f['name']}: {pyt}")
        names = [f["name"] for f in m["fields"]]
        o += ["", "    def pack(self) -> bytes:"]
        o.append(f"        return self._STRUCT.pack({', '.join('self.' + n for n in names)})")
        o += ["", "    @classmethod", f'    def unpack(cls, payload: bytes) -> "{cls}":']
        if names:
            o.append(f"        {', '.join(names)}{',' if len(names) == 1 else ''} = cls._STRUCT.unpack(payload)")
            args = [f"{f['enum']}({f['name']})" if "enum" in f else f["name"] for f in m["fields"]]
            o.append(f"        return cls({', '.join(args)})")
        else:
            o += ["        cls._STRUCT.unpack(payload)", "        return cls()"]
        o += ["", "    def encode(self) -> bytes:", "        return encode(self.TYPE, self.pack())", "", ""]

    o.append("MESSAGES: Dict[int, Type] = {")
    for name in s["messages"]:
        o.append(f"    {name}: {camel(name)},")
    o += ["}", "", ""]

    o += [
        "def decode(msg_type: int, payload: bytes):",
        '    """Typed message for a parsed frame, or None if the type or length is unknown."""',
        "    cls = MESSAGES.get(msg_type)",
        "    if cls is None or len(payload) != cls.LEN:",
        "        return None",
        "    try:",
        "        return cls.unpack(payload)",
        "    except ValueError:  # e.g. a State value this side does not know",
        "        return None",
        "",
        "",
        "class Parser:",
        '    """Feed it raw bytes; it yields (type, payload) for every frame with a good CRC."""',
        "",
        "    def __init__(self) -> None:",
        "        self._buf = bytearray()",
        "        self.crc_errors = 0",
        "",
        "    def feed(self, data: bytes) -> Iterator[Tuple[int, bytes]]:",
        "        buf = self._buf",
        "        buf.extend(data)",
        "        while True:",
        "            start = buf.find(SYNC)",
        "            if start < 0:",
        "                # keep a trailing SYNC0, it may be the start of the next frame",
        "                del buf[: len(buf) - 1 if buf[-1:] == bytes([SYNC0]) else len(buf)]",
        "                return",
        "            del buf[:start]",
        "            if len(buf) < 4:",
        "                return",
        "            n = buf[3]",
        "            if n > MAX_PAYLOAD:",
        "                del buf[:2]",
        "                continue",
        "            if len(buf) < n + 5:",
        "                return",
        "            body = bytes(buf[2 : 4 + n])",
        "            if crc8(body) == buf[4 + n]:",
        "                del buf[: n + 5]",
        "                yield body[0], body[2:]",
        "            else:",
        "                self.crc_errors += 1",
        "                del buf[:2]",
        "",
        "    def messages(self, data: bytes) -> Iterator[object]:",
        '        """Like feed(), but yields typed messages and skips unknown ones."""',
        "        for t, p in self.feed(data):",
        "            m = decode(t, p)",
        "            if m is not None:",
        "                yield m",
        "",
    ]
    return "\n".join(o)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if the generated files are out of date")
    a = ap.parse_args()
    s = load()
    stale = []
    for path, text in ((OUT_H, gen_h(s)), (OUT_PY, gen_py(s))):
        rel = path.relative_to(ROOT)
        current = path.read_text() if path.exists() else None
        if current == text:
            print(f"up to date  {rel}")
        elif a.check:
            stale.append(rel)
            print(f"OUT OF DATE {rel}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
            print(f"wrote       {rel}")
    if stale:
        print("Run: python3 comms/gen_protocol.py")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
